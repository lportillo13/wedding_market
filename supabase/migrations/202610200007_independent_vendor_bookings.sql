CREATE OR REPLACE VIEW public.rfqs_visible WITH (security_barrier=true) AS
SELECT r.id,
  r.owner_id,
  r.created_at,
  r.event_date,
  r.guest_count,
  r.budget_min,
  r.budget_max,
  r.city,
  r.state,
  r.country,
  r.language,
  r.theme,
  r.notes,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' THEN r.accepted_quote_id ELSE consent.accepted_quote_id END AS accepted_quote_id,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' THEN r.accepted_at ELSE consent.accepted_at END AS accepted_at,
  r.updated_at,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' OR consent.email THEN r.contact_email END AS contact_email,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' OR consent.phone THEN r.contact_phone END AS contact_phone,
  r.flexible_date,
  r.guest_count_range,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' OR consent.booked THEN r.guest_first_name END AS guest_first_name,
  CASE WHEN r.owner_id=auth.uid() OR auth.role()='service_role' OR consent.booked THEN r.guest_last_name END AS guest_last_name,
