LEFT JOIN LATERAL (
 SELECT bool_or(i.reveal_email) AS email,bool_or(i.reveal_phone) AS phone,bool_or(true) AS booked,max(i.accepted_quote_id::text)::uuid AS accepted_quote_id,max(i.accepted_at) AS accepted_at
 FROM public.rfq_invites i JOIN public.vendors v ON v.id=i.vendor_id
 JOIN public.quotes q ON q.id=i.accepted_quote_id AND q.vendor_id=i.vendor_id
 WHERE i.rfq_id=r.id AND v.owner_id=auth.uid()
