import fs from 'node:fs';
const license=fs.readFileSync('mobile/node_modules/@expo-google-fonts/playfair-display/LICENSE_FONT','utf8').replace(/\r/g,'');
if(!license.includes('SIL OPEN FONT LICENSE Version 1.1'))throw Error('Unexpected bundled font license.');
fs.writeFileSync('mobile/src/content/font-license.ts','// Generated by scripts/generate-native-notices.mjs from the installed font package.\nexport const fontLicense = '+JSON.stringify(license)+';\n');
console.log('Bundled Playfair font license copied into native source.');
